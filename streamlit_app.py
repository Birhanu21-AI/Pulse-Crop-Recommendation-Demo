import os

import requests
import streamlit as st

API_URL = os.getenv("API_URL", "http://localhost:8000")

st.set_page_config(page_title="Pulse Crop Recommendation App", page_icon="🌱",
                   layout="wide",)
st.title("🌱Pulse Crop Recommendation App")
st.markdown("An AI-powered crop recommendation tool based on soil and environmental conditions.")

#Intended use and limitations
with st.expander("About this tool: intended use and limitations"):
    st.markdown(
        "Intended users: Farmers will use the system to receive a preliminary"
        "recommendation among four supported pulse crops."
        "The application will help users make more informed crop-selection"
        "decisions by providing a machine-learning-based crop recommendation.\n\n"
        "What the result means: a crop recommendation generated by a "
        "Random Forest machine-learning model using soil nutrient levels "
        "and environmental conditions.\n\n"
        "Limitations: recommendations are based on patterns learned from "
        "the model's training dataset and may not fully reflect local "
        "agricultural conditions. The application does not guarantee crop "
        "yield or successful harvests and does not replace professional "
        "agricultural advice. Farmers remain responsible for their "
        "cultivation decisions."
    )
# Create the input form in the sidebar
with st.sidebar:
    st.header("Soil and Environmental Information")

    N = st.number_input(
        "Nitrogen (N)",
        min_value=0.0,
        max_value=200.0,
        value=90.0,
        step=1.0,
        help="Enter the nitrogen content measured in your soil test."
    )

    P = st.number_input(
        "Phosphorus (P)",
        min_value=0.0,
        max_value=100.0,
        value=42.0,
        step=1.0,
        help="Enter the phosphorus content measured in your soil test."
    )

    K = st.number_input(
        "Potassium (K)",
        min_value=0.0,
        max_value=300.0,
        value=43.0,
        step=1.0,
        help="Enter the potassium content measured in your soil test."
    )

    temperature = st.number_input(
        "Temperature (°C)",
        min_value=-10.0,
        max_value=50.0,
        value=20.5,
        step=0.1,
        help="Enter the environmental temperature in degrees Celsius."
    )

    humidity = st.number_input(
        "Humidity (%)",
        min_value=0.0,
        max_value=100.0,
        value=82.0,
        step=1.0,
        help="Enter the relative humidity percentage (0–100%)."
    )

    ph = st.number_input(
        "Soil pH",
        min_value=0.0,
        max_value=14.0,
        value=6.5,
        step=0.1,
        help="Enter the soil pH value (0–14)."
    )

    rainfall = st.number_input(
        "Rainfall (mm)",
        min_value=0.0,
        max_value=500.0,
        value=100.0,
        step=1.0,
        help="Enter the rainfall measurement in millimetres."
    )

    submit = st.button(
        "Recommend Crop",
        type="primary",
        use_container_width=True
    )

    # Training range warning
    # Check whether inputs fall outside the model's training-data ranges

training_ranges = {
    "Nitrogen (N)": (0, 60, N),
    "Phosphorus (P)": (35, 80, P),
    "Potassium (K)": (15, 85, K),
    "Temperature (°C)": (15.33, 29.94, temperature),
    "Humidity (%)": (14.26, 90, humidity),
    "Soil pH": (5.50, 8.87, ph),
    "Rainfall (mm)": (35.03, 149.74, rainfall)
}

out_of_range = []

for parameter, (minimum, maximum, value) in training_ranges.items():

    if value < minimum or value > maximum:

        out_of_range.append(
            f"- **{parameter}:** {value} "
            f"(Training range: {minimum}–{maximum})"
        )

if out_of_range:

    st.warning(
        "**Some input values are outside the model's training-data ranges.** "
        "The prediction may be less reliable for these conditions.\n\n"
        + "\n\n".join(out_of_range)
    )
    
    # Part 2: The call to the API

if submit:
    payload = {
        "N": N,
        "P": P,
        "K": K,
        "temperature": temperature,
        "humidity": humidity,
        "ph": ph,
        "rainfall": rainfall
    }

    # Step 4: Error handling
    try:
        with st.spinner("Generating your crop recommendation. Please wait..."):
            r = requests.post(
                f"{API_URL}/predict",
                json=payload,
                timeout=60
            )

    except requests.exceptions.Timeout:
        st.error(
            "The service took too long to answer. "
            "Please wait a moment and try again."
        )
        st.stop()

    except requests.exceptions.RequestException:
        st.error(
            "Could not reach the service. "
            "Check your connection and try again."
        )
        st.stop()
# Part 3: Displaying the result
    if r.status_code == 200:
        try:
            result = r.json()
            recommended_crop = str(result["recommended_crop"])
            confidence = float(result["confidence"])
            model_version = str(result["model_version"])

        except (ValueError, KeyError, TypeError):
            st.error(
                "The service sent a response that could not be read. "
                "Please try again later."
            )
            st.stop()

        c1, c2, c3 = st.columns(3)

        c1.metric("Recommended Crop", recommended_crop.upper())
        c2.metric("Model Confidence", f"{confidence:.1%}")
        c3.metric("Model Version", model_version)

if r.status_code == 200:
    try:
        result = r.json()
        recommended_crop = str(result["recommended_crop"])
        confidence = float(result["confidence"])
        model_version = str(result["model_version"])

    except (ValueError, KeyError, TypeError):
        st.error(
            "The service sent an answer that could not be read. "
            "Please try again later."
        )
        st.stop()

    c1, c2, c3 = st.columns(3)

    c1.metric("Recommended Crop", recommended_crop.upper())
    c2.metric("Model Confidence", f"{confidence:.1%}")
    c3.metric("Model Version", model_version)

# Adding step 4 error handling in part 3
    st.write(
        f"Based on the soil and environmental information provided, "
        f"the recommended crop is **{recommended_crop.upper()}**."
    )

    st.info(
        "This recommendation is generated by a machine-learning model. "
        "It supports agricultural decision-making but does not guarantee "
        "crop productivity or successful harvests."
    )

elif r.status_code == 422:
    st.warning(
        "Some inputs are invalid. Please check the values and try again."
    )

else:
    st.error(
        "The service returned an error. Please try again later."
    )
